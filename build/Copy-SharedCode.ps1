#Requires -Version 7.4

<#
.SYNOPSIS
    Copies the repository's shared PowerShell into a built module's Private/ folder and records which
    state of shared/ the module was built from.

.DESCRIPTION
    Every component module carries its own copy of shared/: shared/powershell/*.ps1 lands in Private/,
    shared/js is compiled into the bundle. Private/SHARED.txt names that state: one SHA-256 over all
    files below shared/ and one line per file, so two built modules (or two releases) can be compared
    without unpacking the bundle. Content hashes, not a git commit: they also hold for a build from an
    uncommitted checkout or an unpacked release zip.

.PARAMETER Destination
    The Private/ folder of the built module; created when missing.

.PARAMETER SharedPath
    The shared/ folder. Default: shared/ in the repository.

.EXAMPLE
    ./build/Copy-SharedCode.ps1 -Destination output/PowerShellUniversal.Component.Pivot/0.1.0/Private

.OUTPUTS
    System.IO.FileInfo of SHARED.txt.
#>
[CmdletBinding()]
[OutputType([System.IO.FileInfo])]
param(
    [Parameter(Mandatory)][string]$Destination,
    [string]$SharedPath = (Join-Path $PSScriptRoot '..' 'shared')
)
$ErrorActionPreference = 'Stop'

$shared = (Resolve-Path -LiteralPath $SharedPath).Path
New-Item -ItemType Directory -Path $Destination -Force | Out-Null
Copy-Item -Path (Join-Path $shared 'powershell' '*.ps1') -Destination $Destination

# relative paths with "/" in ordinal order, so the record is the same on every platform
$lines = [System.Collections.Generic.List[string]]::new()
foreach ($file in Get-ChildItem -LiteralPath $shared -Recurse -File) {
    if ($file.Name -match '^(\._|\.DS_Store$)') { continue }
    $path = [System.IO.Path]::GetRelativePath($shared, $file.FullName).Replace('\', '/')
    $lines.Add(('{0}  {1}' -f (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant(), $path))
}
$lines.Sort([System.Comparison[string]] { param($a, $b) [string]::CompareOrdinal($a.Substring(66), $b.Substring(66)) })
$sha = [System.Security.Cryptography.SHA256]::Create()
try { $total = -join ($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($lines -join "`n")) | ForEach-Object { $_.ToString('x2') }) }
finally { $sha.Dispose() }

$record = Join-Path $Destination 'SHARED.txt'
$text = @(
    '# The state of shared/ this module was built from (generated by build/Copy-SharedCode.ps1).'
    '# shared/powershell/*.ps1 is in this folder, shared/js is compiled into the bundle.'
    ('shared {0}' -f $total)
    $lines
) -join "`n"
Set-Content -LiteralPath $record -Value $text -Encoding utf8NoBOM
Get-Item -LiteralPath $record
