// The documentation site draws the modules' own components (docs/site/src/charts.jsx), with packages
// from its own package.json. They must be the versions the modules ship, or a page shows a chart the
// module does not draw. Dependabot updates each folder on its own, so this test ties them together.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, existsSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, root), "utf8"));

test("the site's packages have the versions the modules pin", () => {
    const site = read("docs/site/package.json").dependencies;
    const modules = readdirSync(new URL("modules/", root), { withFileTypes: true })
        .filter((d) => d.isDirectory() && existsSync(new URL(`modules/${d.name}/package.json`, root)))
        .map((d) => [d.name, read(`modules/${d.name}/package.json`)]);
    for (const [name, version] of Object.entries(site)) {
        for (const [module, pkg] of modules) {
            const pinned = pkg.dependencies?.[name] ?? pkg.devDependencies?.[name];
            if (pinned !== undefined) assert.equal(version, pinned, `docs/site/package.json pins ${name} ${version}, ${module} ${pinned}`);
        }
    }
});
